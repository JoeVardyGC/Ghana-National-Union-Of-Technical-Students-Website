export async function initializeDatabase(): Promise<{ success: boolean; message: string }> {
  try {
    const dialect = getDialect();
    if (dialect === 'postgres') await createPostgresSchema();
    else if (dialect === 'mysql') await createMysqlSchema();
    else await ensureSiteSettingsTable();

    await seedStarterContent();

    const label = dialect === 'postgres' ? 'PostgreSQL (Supabase)' : dialect === 'mysql' ? 'MySQL' : 'local JSON store';
    return { success: true, message: `All GNUTS database tables verified and initialized (${label}).` };
  } catch (error) {
    return { success: false, message: (error as Error)?.message || 'Database initialization error' };
  }
}
