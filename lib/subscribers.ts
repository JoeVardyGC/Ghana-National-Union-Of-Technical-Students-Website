import { getDialect, query } from '@/lib/db';

/**
 * People who signed up for GNUTS scholarship & opportunity alerts (the "Get free
 * alerts" box on the Scholarships page). Server-only.
 *
 * Admins see and export the list in Admin > Alert Subscribers, then send updates
 * from the union's email (e.g. Gmail BCC or Mailchimp) or WhatsApp broadcast list.
 */

export interface Subscriber {
  id: number;
  contact: string;
  contact_type: 'email' | 'phone' | string;
  source: string;
  created_at: string;
}

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

// The table is created the first time it is needed; re-checked at most once a minute
const ENSURE_TTL_MS = 60_000;
let lastEnsured = 0;

export async function ensureSubscribersTable(): Promise<void> {
  if (Date.now() - lastEnsured < ENSURE_TTL_MS) return;
  const isPostgres = getDialect() === 'postgres';
  await query(`
    CREATE TABLE IF NOT EXISTS subscribers (
      id ${isPostgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INT AUTO_INCREMENT PRIMARY KEY'},
      contact VARCHAR(190) NOT NULL,
      contact_type VARCHAR(10) NOT NULL,
      source VARCHAR(60) DEFAULT 'scholarships',
      created_at ${isPostgres ? 'TIMESTAMPTZ NOT NULL DEFAULT now()' : 'TIMESTAMP DEFAULT CURRENT_TIMESTAMP'}
    )${isPostgres ? '' : ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4'}
  `);
  lastEnsured = Date.now();
}

/**
 * Checks an email address or Ghanaian/international phone number.
 * Returns the cleaned value and its type, or an error message.
 */
export function parseContact(raw: unknown): { contact: string; type: 'email' | 'phone' } | string {
  const value = typeof raw === 'string' ? raw.trim().slice(0, 190) : '';
  if (!value) return 'Please enter your email address or phone number.';

  if (value.includes('@')) {
    const email = value.toLowerCase();
    return EMAIL_PATTERN.test(email) ? { contact: email, type: 'email' } : 'Please enter a valid email address.';
  }

  const digits = value.replace(/[^\d+]/g, '');
  const count = digits.replace(/\D/g, '').length;
  if (count < 9 || count > 15) return 'Please enter a valid phone number (e.g. 024 123 4567).';
  return { contact: digits, type: 'phone' };
}

export async function listSubscribers(): Promise<Subscriber[]> {
  await ensureSubscribersTable();
  const rows = await query<Subscriber>('SELECT * FROM subscribers ORDER BY created_at DESC, id DESC');
  return (rows || []).map((row) => ({
    id: Number(row.id),
    contact: String(row.contact || ''),
    contact_type: String(row.contact_type || ''),
    source: String(row.source || ''),
    created_at: row.created_at ? new Date(row.created_at).toISOString() : '',
  }));
}

/** Saves a sign-up. Returns false when the contact was already on the list. */
export async function addSubscriber(contact: string, type: string, source: string): Promise<boolean> {
  await ensureSubscribersTable();
  // Checked in code as well, since the local development store has limited WHERE support
  const existing = await query<Subscriber>('SELECT * FROM subscribers');
  if ((existing || []).some((row) => String(row.contact).toLowerCase() === contact.toLowerCase())) return false;
  await query('INSERT INTO subscribers (contact, contact_type, source) VALUES (?, ?, ?)', [contact, type, source]);
  return true;
}

export async function deleteSubscriber(id: number): Promise<void> {
  await ensureSubscribersTable();
  await query('DELETE FROM subscribers WHERE id = ?', [id]);
}
