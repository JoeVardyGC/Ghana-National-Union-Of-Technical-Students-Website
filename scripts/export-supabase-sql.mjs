#!/usr/bin/env node
/**
 * Writes supabase-import.sql: the full PostgreSQL schema plus the content of
 * data/gnuts_db.json, ready to paste into Supabase > SQL Editor > Run.
 * (Browser-only alternative to running init-db + copy-local-data-to-database.mjs.)
 *
 * Usage: node scripts/export-supabase-sql.mjs [--file data/gnuts_db.json] [--out supabase-import.sql]
 *
 * The table definitions are read from lib/dbInit.ts so this always matches what the site creates.
 * User accounts are not exported: the first admin is created automatically on first login
 * from ADMIN_EMAIL / ADMIN_PASSWORD.
 */
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const opt = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const dataFile = path.resolve(opt('--file', 'data/gnuts_db.json'));
const outFile = path.resolve(opt('--out', 'supabase-import.sql'));

const TABLES = [
  'site_settings', 'about_page', 'history_milestones', 'hero_banners', 'news', 'scholarships',
  'opportunities', 'innovations', 'resources', 'executives', 'gallery', 'contact_messages', 'audit_logs',
];
const SITE_SETTINGS_FILL = { mobile_phone: '+233 24 316 3135', postal_address: 'P.O. Box GP 2329, Accra - Ghana' };

const SITE_SETTINGS_DDL = `
    CREATE TABLE IF NOT EXISTS site_settings (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      portal_name VARCHAR(255) NOT NULL,
      secretariat_email VARCHAR(190) NOT NULL,
      hotline_phone VARCHAR(60) NOT NULL,
      mobile_phone VARCHAR(60) DEFAULT '',
      headquarters_address VARCHAR(255) NOT NULL,
      postal_address VARCHAR(255) DEFAULT '',
      facebook_url VARCHAR(255) DEFAULT '',
      twitter_url VARCHAR(255) DEFAULT '',
      instagram_url VARCHAR(255) DEFAULT '',
      tiktok_url VARCHAR(255) DEFAULT '',
      linkedin_url VARCHAR(255) DEFAULT '',
      youtube_url VARCHAR(255) DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )`;

// --- Schema from lib/dbInit.ts --------------------------------------------
const dbInit = fs.readFileSync(path.resolve('lib/dbInit.ts'), 'utf8');
const pgBlock = dbInit.slice(dbInit.indexOf('const PG_TABLES'), dbInit.indexOf('async function createPostgresSchema'));
const ddl = {};
for (const m of pgBlock.matchAll(/(\w+): `([\s\S]*?)`/g)) ddl[m[1]] = m[2];
ddl.site_settings = SITE_SETTINGS_DDL;
if (!ddl.news || !ddl.users) throw new Error('Could not read the table definitions from lib/dbInit.ts');

/** column -> { type, nullable } parsed from a CREATE TABLE statement */
function columnsOf(createSql) {
  const cols = {};
  for (const line of createSql.split('\n')) {
    const m = line.trim().match(/^([a-z_0-9]+)\s+([A-Z]+)/);
    if (!m || m[1] === 'create') continue;
    cols[m[1]] = { type: m[2], nullable: !/NOT NULL|PRIMARY KEY/.test(line) };
  }
  return cols;
}

// --- SQL literals ------------------------------------------------------------
const str = (v) => `'${String(v).replace(/'/g, "''")}'`;
function literal(value, col) {
  if (value === undefined) return undefined;
  if (value === null) return col.nullable ? 'NULL' : undefined;
  switch (col.type) {
    case 'DATE':
    case 'TIMESTAMPTZ':
      if (value === '' || Number.isNaN(new Date(value).getTime())) return col.nullable ? 'NULL' : undefined;
      return str(value);
    case 'INTEGER':
    case 'SMALLINT':
    case 'BIGINT':
      if (typeof value === 'boolean') return value ? '1' : '0';
      if (value === '' || Number.isNaN(Number(value))) return col.nullable ? 'NULL' : undefined;
      return String(Math.trunc(Number(value)));
    case 'JSONB':
      return `${str(typeof value === 'string' ? value : JSON.stringify(value))}::jsonb`;
    default:
      return str(typeof value === 'object' ? JSON.stringify(value) : value);
  }
}

// --- Build the file ------------------------------------------------------------
const data = JSON.parse(fs.readFileSync(dataFile, 'utf8'));
const out = [];
const counts = [];
out.push(
  '-- GNUTS: schema + content for Supabase',
  `-- Generated ${new Date().toISOString()} from ${path.basename(dataFile)}`,
  '-- Paste everything into Supabase > SQL Editor > New query, then click Run.',
  '-- Safe to run more than once: existing rows with the same id are updated, not duplicated.',
  '-- User accounts are not included: sign in at /admin/login with ADMIN_EMAIL / ADMIN_PASSWORD',
  '-- and the first admin account is created automatically.',
  '',
  'BEGIN;',
  '',
  '-- 1. Tables'
);
for (const [table, sql] of Object.entries(ddl)) out.push(`${sql.trim()};`, '');

out.push(
  '-- 2. Keep updated_at current on every change',
  'CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$',
  'BEGIN',
  '  NEW.updated_at = now();',
  '  RETURN NEW;',
  'END;',
  '$$ LANGUAGE plpgsql;',
  ''
);
for (const [table, sql] of Object.entries(ddl)) {
  if (/updated_at/.test(sql)) {
    out.push(
      `DROP TRIGGER IF EXISTS ${table}_set_updated_at ON ${table};`,
      `CREATE TRIGGER ${table}_set_updated_at BEFORE UPDATE ON ${table} FOR EACH ROW EXECUTE FUNCTION set_updated_at();`
    );
  }
}
out.push('', "-- 3. Block Supabase's public REST API (the website connects as the owner and is unaffected)");
for (const table of Object.keys(ddl)) out.push(`ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY;`);

out.push('', '-- 4. Content');
for (const table of TABLES) {
  const rows = Array.isArray(data[table]) ? data[table] : [];
  if (!rows.length) continue;
  const cols = columnsOf(ddl[table]);
  out.push('', `-- ${table}: ${rows.length} row(s)`);
  for (const raw of rows) {
    const row = table === 'site_settings' ? { ...SITE_SETTINGS_FILL, ...raw } : raw;
    const names = [];
    const values = [];
    for (const [name, value] of Object.entries(row)) {
      if (!cols[name]) continue;
      const lit = literal(value, cols[name]);
      if (lit === undefined) continue;
      names.push(name);
      values.push(lit);
    }
    if (!names.includes('id')) continue;
    const updates = names.filter((n) => n !== 'id').map((n) => `${n} = EXCLUDED.${n}`);
    out.push(
      `INSERT INTO ${table} (${names.join(', ')}) VALUES (${values.join(', ')})` +
        ` ON CONFLICT (id) DO ${updates.length ? `UPDATE SET ${updates.join(', ')}` : 'NOTHING'};`
    );
  }
  if (table !== 'about_page') {
    out.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM ${table}), 1));`);
  }
  counts.push(`${table} ${rows.length}`);
}

out.push('', 'COMMIT;', '');
fs.writeFileSync(outFile, out.join('\n'), 'utf8');
console.log(`Wrote ${path.relative(process.cwd(), outFile)} (${(fs.statSync(outFile).size / 1024).toFixed(1)} KB)`);
console.log(`Content: ${counts.join(', ')}`);
console.log('Skipped: users (old local accounts), settings (legacy)');
