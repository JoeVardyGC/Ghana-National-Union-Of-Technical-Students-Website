async function createPostgresSchema(): Promise<void> {
  for (const ddl of Object.values(PG_TABLES)) {
    await query(ddl);
  }
  await ensureSiteSettingsTable();

  // Keep updated_at current on every UPDATE (MySQL's ON UPDATE CURRENT_TIMESTAMP)
  await query(`
    CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
    BEGIN
      NEW.updated_at = now();
      RETURN NEW;
    END;
    $$ LANGUAGE plpgsql
  `);

  const tables = [...Object.keys(PG_TABLES), 'site_settings'];
  for (const table of tables) {
    const hasUpdatedAt = table === 'site_settings' || /updated_at/.test(PG_TABLES[table] || '');
    if (hasUpdatedAt) {
      await query(`DROP TRIGGER IF EXISTS ${table}_set_updated_at ON ${table}`);
      await query(
        `CREATE TRIGGER ${table}_set_updated_at BEFORE UPDATE ON ${table} FOR EACH ROW EXECUTE FUNCTION set_updated_at()`
      );
    }
    // Supabase exposes public tables through its REST API. Row Level Security with
    // no policies blocks that API completely; this app connects as the table owner,
    // which is not affected.
    await query(`ALTER TABLE ${table} ENABLE ROW LEVEL SECURITY`);
  }
}

// ---------------------------------------------------------------------------
// MySQL schema (unchanged behaviour, for existing MySQL deployments)
// ---------------------------------------------------------------------------
async function createMysqlSchema(): Promise<void> {
  const mysqlDdl = Object.values(PG_TABLES).map((ddl) =>
    ddl
      .replace(/INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g, 'INT AUTO_INCREMENT PRIMARY KEY')
      .replace(/TIMESTAMPTZ NOT NULL DEFAULT now\(\)/g, 'TIMESTAMP DEFAULT CURRENT_TIMESTAMP')
      .replace(/DATE DEFAULT CURRENT_DATE/g, 'DATE DEFAULT (CURRENT_DATE)')
      .replace(/\bJSONB\b/g, 'JSON')
      .replace(/\bTEXT NOT NULL DEFAULT ''/g, 'TEXT NOT NULL')
      .replace(/\bTEXT\b(?! NOT NULL)/g, 'LONGTEXT')
      .replace(/updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP/g, 'updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP')
      .concat(' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4')
  );
  for (const ddl of mysqlDdl) await query(ddl);

  // Columns added after the first release
  await query('ALTER TABLE users ADD COLUMN name VARCHAR(150) DEFAULT NULL').catch(() => null);
  await query('ALTER TABLE contact_messages ADD COLUMN name VARCHAR(150) DEFAULT NULL').catch(() => null);
  await query('ALTER TABLE contact_messages MODIFY COLUMN full_name VARCHAR(150) DEFAULT NULL').catch(() => null);

  // Older MySQL tables used VARCHAR(255) for images; widen them for CDN URLs and inline images
  const longTextColumns: [string, string][] = [
    ['innovations', 'project_image'], ['news', 'image'], ['news', 'image2'], ['news', 'image3'],
    ['executives', 'photo'], ['hero_banners', 'image_url'], ['gallery', 'image'], ['resources', 'file_path'],
    ['about_page', 'hero_image'], ['about_page', 'who_we_are_image'], ['users', 'avatar'],
  ];
  for (const [table, column] of longTextColumns) {
    await query(`ALTER TABLE ${table} MODIFY COLUMN ${column} LONGTEXT`).catch(() => null);
  }

  await ensureSiteSettingsTable();
}

